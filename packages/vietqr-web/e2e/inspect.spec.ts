import AxeBuilder from "@axe-core/playwright";
import { expect, test, type Page } from "@playwright/test";
import { API_URL } from "../playwright.config";

const API = `${API_URL}/api/v1/vietqr-core`;
const QS = new URLSearchParams({
  bankBin: "970436",
  accountNo: "0011004",
  amount: "50000",
  description: "cafe sang",
});

// Next.js adds its own route-announcer role=alert; exclude it.
const alert = (page: Page) =>
  page.locator('[role="alert"]:not(#__next-route-announcer__)');

test("round trip: a QR generated by the API is read back by Inspect", async ({
  page,
  request,
}) => {
  const res = await request.get(`${API}/image?${QS}&template=qr_only`);
  expect(res.ok()).toBeTruthy();
  const buffer = Buffer.from(await res.body());

  await page.goto("/inspect");
  await page
    .getByLabel("Choose image")
    .setInputFiles({ name: "qr.png", mimeType: "image/png", buffer });

  await expect(page.getByText("Checksum valid")).toBeVisible();
  await expect(page.getByText("Vietcombank")).toBeVisible();
  await expect(page.getByText("0011004", { exact: true })).toBeVisible();
  await expect(page.getByText(/50[.,]000/)).toBeVisible();
  await expect(page.getByText("cafe sang", { exact: true })).toBeVisible();
  await expect(
    page.getByRole("link", { name: "Create similar QR" }),
  ).toHaveAttribute(
    "href",
    "/?bank=VCB&account=0011004&amount=50000&description=cafe+sang",
  );

  const a11y = await new AxeBuilder({ page })
    .withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"])
    .analyze();
  expect(a11y.violations).toEqual([]);
});

test("round trip: a static QR is read back as static, and Create similar QR omits the amount", async ({
  page,
  request,
}) => {
  const qs = new URLSearchParams({ bankBin: "970436", accountNo: "0011004" });
  const res = await request.get(`${API}/image?${qs}&template=qr_only`);
  expect(res.ok()).toBeTruthy();
  const buffer = Buffer.from(await res.body());

  await page.goto("/inspect");
  await page
    .getByLabel("Choose image")
    .setInputFiles({ name: "qr.png", mimeType: "image/png", buffer });

  await expect(page.getByText("Checksum valid")).toBeVisible();
  await expect(page.getByText("0011004", { exact: true })).toBeVisible();
  await expect(page.getByText("Static", { exact: true })).toBeVisible();
  await expect(page.getByText(/^Not set/)).toBeVisible();
  await expect(
    page.getByRole("link", { name: "Create similar QR" }),
  ).toHaveAttribute("href", "/?bank=VCB&account=0011004");
});

test("pasting the Payload gives the same breakdown; a corrupted checksum is refused", async ({
  page,
  request,
}) => {
  const gen = await request.get(`${API}/generate?${QS}`);
  const { data } = await gen.json();
  const payload: string = data.qrCode;

  await page.goto("/inspect");
  await page.getByLabel("Payload", { exact: true }).fill(payload);
  await page.getByRole("button", { name: "Read payload" }).click();
  await expect(page.getByText("Checksum valid")).toBeVisible();
  await expect(page.getByText("0011004", { exact: true })).toBeVisible();

  const bad = payload.slice(0, -1) + (payload.endsWith("0") ? "1" : "0");
  await page.getByLabel("Payload", { exact: true }).fill(bad);
  await page.getByRole("button", { name: "Read payload" }).click();
  // The API refuses a payload whose checksum does not match (code 07).
  await expect(alert(page)).toContainText("not a valid VietQR code");
  await page.getByText("Technical detail").click();
  await expect(alert(page)).toContainText("CRC");
});

test("a non-VietQR payload and an unreadable image show errors", async ({
  page,
}) => {
  await page.goto("/inspect");
  await page.getByLabel("Payload", { exact: true }).fill("hello world");
  await page.getByRole("button", { name: "Read payload" }).click();
  await expect(alert(page)).toContainText("not a valid VietQR code");

  await page.getByLabel("Choose image").setInputFiles({
    name: "blank.png",
    mimeType: "image/png",
    buffer: Buffer.from(
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==",
      "base64",
    ),
  });
  await expect(alert(page)).toContainText("Could not read");
});

test("dropzone is keyboard reachable and an oversized file is refused client-side", async ({
  page,
}) => {
  await page.goto("/inspect");
  await page.getByLabel("Payload", { exact: true }).focus();
  await page.keyboard.press("Tab"); // submit button
  await page.keyboard.press("Tab");
  await expect(page.getByLabel("Choose image")).toBeFocused();

  let decodeCalls = 0;
  page.on("request", (r) => {
    if (r.url().includes("/decode")) decodeCalls++;
  });
  await page.getByLabel("Choose image").setInputFiles({
    name: "big.png",
    mimeType: "image/png",
    buffer: Buffer.alloc(8 * 1024 * 1024 + 1),
  });
  await expect(alert(page)).toContainText("too large");
  expect(decodeCalls).toBe(0);
});
