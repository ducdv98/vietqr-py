// Generates src/lib/api/schema.d.ts and version.ts from the API's OpenAPI document.
//   node scripts/gen-api.mjs          write the files
//   node scripts/gen-api.mjs --check  fail (exit 1) if committed files differ (drift)
// The document comes from the python app (`uv run`), or from --spec <file.json>.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(root, "../..");
const check = process.argv.includes("--check");
const specIdx = process.argv.indexOf("--spec");

const specText =
  specIdx > -1
    ? readFileSync(process.argv[specIdx + 1], "utf8")
    : execFileSync(
        "uv",
        ["run", "python", join(root, "scripts/dump-openapi.py")],
        {
          cwd: repo,
          encoding: "utf8",
          maxBuffer: 64 * 1024 * 1024,
        },
      );
const spec = JSON.parse(specText);

const header =
  "// Generated by scripts/gen-api.mjs from the vietqr-api OpenAPI. Do not edit.\n";
const ast = await openapiTS(spec);
const outputs = {
  "src/lib/api/schema.d.ts": header + astToString(ast),
  "src/lib/api/version.ts":
    header +
    `/** Version of vietqr-api this client was generated against (compare with /health). */\n` +
    `export const GENERATED_API_VERSION = ${JSON.stringify(spec.info.version)};\n`,
};

const drifted = [];
for (const [rel, content] of Object.entries(outputs)) {
  const path = join(root, rel);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content)
      drifted.push(rel);
  } else {
    writeFileSync(path, content);
  }
}
if (drifted.length) {
  console.error(
    `API client drift: ${drifted.join(", ")} differ from the API's OpenAPI.\nRun \`pnpm api:generate\` and commit the result.`,
  );
  process.exit(1);
}
console.log(
  check ? "API client is up to date." : "Generated API client files.",
);
